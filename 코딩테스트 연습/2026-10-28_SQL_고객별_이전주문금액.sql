-- 2026-10-28
-- 문제: 각 주문에 대해 같은 고객의 바로 이전 주문 금액을 출력한다.
-- 핵심: LAG + PARTITION BY + ORDER BY

-- ============================================================
-- 1. 문제
-- ============================================================

-- orders
--
-- order_id | customer_id | amount | ordered_at
-- 1        | 101         | 12000  | 2026-10-01 10:00
-- 2        | 102         | 35000  | 2026-10-01 11:00
-- 3        | 101         | 18000  | 2026-10-03 15:00
-- 4        | 103         | 22000  | 2026-10-02 09:00
-- 5        | 102         | 41000  | 2026-10-05 13:00
-- 6        | 101         | 15000  | 2026-10-02 18:00
-- 7        | 103         | 30000  | 2026-10-06 14:00
--
-- 출력:
-- customer_id, order_id, amount, previous_amount, ordered_at
--
-- 같은 고객의 바로 이전 주문 amount를 previous_amount로 표시한다.
-- 첫 주문의 previous_amount는 NULL이다.


-- ============================================================
-- 2. 내가 처음 작성한 쿼리
-- ============================================================

SELECT
    customer_id,
    order_id,
    amount,
    LAG(amount, 1, NULL) OVER (
        ORDER BY ordered_at ASC
    ) AS previous_amount,
    ordered_at
FROM orders
GROUP BY customer_id
ORDER BY `customer_id ASC, ordered_at ASC`;


-- ============================================================
-- 3. 무엇이 맞았는가
-- ============================================================

-- "현재 행에서 이전 행의 값을 가져온다"는 요구를 보고
-- LAG()를 선택한 것은 정확했다.
--
-- LAG(amount, 1, NULL)
-- - amount       : 가져올 컬럼
-- - 1            : 한 행 이전
-- - NULL         : 이전 행이 없을 때 기본값
--
-- 사실 1과 NULL은 기본값이라 LAG(amount)만 써도 된다.


-- ============================================================
-- 4. 왜 그대로는 정답이 아니었는가
-- ============================================================

-- (1) 고객별 범위를 나누지 않았다.
--
-- 처음:
--
-- LAG(amount) OVER (
--     ORDER BY ordered_at
-- )
--
-- 이렇게 하면 "전체 주문"을 시간순으로 놓고 이전 행을 가져온다.
-- 고객이 달라져도 직전 주문 금액이 이어질 수 있다.
--
-- 문제는 "같은 고객의 이전 주문"이므로
--
-- PARTITION BY customer_id
--
-- 로 고객별 윈도우를 나눠야 한다.


-- (2) GROUP BY가 필요하지 않다.
--
-- 이 문제는 여러 행을 하나로 집계하는 문제가 아니다.
-- 주문 행은 그대로 유지하면서 옆에 이전 행의 값을 붙이는 문제다.
--
-- Window Function은 행을 유지한다.
-- GROUP BY는 행을 그룹 단위로 줄인다.
--
-- 따라서 이번 문제에서는 GROUP BY를 제거한다.


-- (3) ORDER BY 문법
--
-- 처음:
-- ORDER BY `customer_id ASC, ordered_at ASC`
--
-- 정렬식 전체를 백틱으로 묶으면 안 된다.
--
-- 수정:
-- ORDER BY customer_id ASC, ordered_at ASC


-- ============================================================
-- 5. 수정한 풀이
-- ============================================================

SELECT
    customer_id,
    order_id,
    amount,
    LAG(amount) OVER (
        PARTITION BY customer_id
        ORDER BY ordered_at ASC
    ) AS previous_amount,
    ordered_at
FROM orders
ORDER BY
    customer_id ASC,
    ordered_at ASC;


-- ============================================================
-- 6. 기억할 패턴
-- ============================================================

-- 이전 행 값:
-- LAG()
--
-- 다음 행 값:
-- LEAD()
--
-- 누구별로 따로 계산할 것인가:
-- PARTITION BY
--
-- 어떤 순서에서 이전/다음을 정의할 것인가:
-- ORDER BY
--
