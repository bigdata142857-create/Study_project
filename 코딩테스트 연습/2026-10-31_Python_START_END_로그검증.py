# 검증 로직이 되지 않았다.


# ============================================================
# 2. 두 번째 시도
# ============================================================

# START일 때 작업명만 저장하도록 수정했다.
#
# result = ["A", "B"]
#
# 하지만 END 시
#
# k[1] in result
#
# 만 확인하면 END A도 허용될 수 있다.
#
# 이 문제는 단순 존재 여부가 아니라
# "가장 최근 START한 작업"이 먼저 END되어야 한다.


# ============================================================
# 3. 핵심 아이디어
# ============================================================

# result[-1]
# -> 가장 최근에 시작한 작업
#
# END 작업명이 result[-1]과 다르면 즉시 False
#
# END가 맞으면 맨 마지막 값을 제거
# -> Stack의 pop()


# ============================================================
# 4. 최종 풀이
# ============================================================

def validate_logs(logs):
    result = []

    for i in logs:
        action, job = i.split()

        if action == "START":
            result.append(job)

        elif action == "END":
            # 시작된 작업이 없는데 END
            if len(result) == 0:
                return False

            # 가장 최근 작업과 다른 작업을 종료
            if job != result[-1]:
                return False

            result.pop()

    # 아직 종료되지 않은 작업이 남아 있으면 False
    if len(result) != 0:
        return False

    return True


print(validate_logs(logs))


