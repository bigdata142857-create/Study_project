# 문제: 서로 다른 두 거래 금액의 합이 target이 되는 인덱스를 반환한다.
# 이중 for문 없이 dict를 사용한다.
# 핵심: Hash / 값 -> 인덱스 / 필요한 상대값 찾기

transactions = [12000, 35000, 8000, 27000, 15000, 20000]
target = 47000


# ============================================================
