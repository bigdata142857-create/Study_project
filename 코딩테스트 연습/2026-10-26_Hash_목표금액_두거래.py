# ============================================================
# 2. 왜 이 방향으로는 어려운가
# ============================================================

# 현재 금액을 알고 있을 때 필요한 것은
# "이 금액의 인덱스가 무엇인가?"이다.
#
# 예:
# current = 35000
# target = 47000
#
# need = 47000 - 35000
#      = 12000
#
# 따라서 빠르게 확인하고 싶은 것은
# "12000을 이전에 본 적이 있는가?"
#
# 그러므로 dict는
#
# 금액 -> 인덱스
#
# 형태가 더 적합하다.


# ============================================================
# 3. 내가 완성한 풀이
# ============================================================

def find_transactions_first(transactions, target):
    dic = {}
    result = []

    for key in range(len(transactions)):
        current = transactions[key]
        need = target - current

        if need in dic:
            result.extend([dic[need], key])
            break
        else:
            dic[current] = key

    return result


print(find_transactions_first(transactions, target))


# ============================================================
# 4. 평가
# ============================================================

# 위 풀이는 정답이다.
#
# 실행:
#
# 1회차
# current = 12000
# need = 35000
# 35000은 dic에 없음
# -> dic[12000] = 0
#
# 2회차
# current = 35000
# need = 12000
# 12000은 dic에 있음
# -> [dic[12000], 1]
# -> [0, 1]


# ============================================================
# 5. 더 간결한 풀이
# ============================================================

def find_transactions(transactions, target):
    seen = {}

    for i in range(len(transactions)):
        current = transactions[i]
        need = target - current

        if need in seen:
            return [seen[need], i]

        seen[current] = i


print(find_transactions(transactions, target))


# ============================================================
# 6. 개선 포인트
# ============================================================

# (1) key라는 변수명보다 i가 더 자연스럽다.
# 현재 반복 변수는 dict key가 아니라 리스트 인덱스이기 때문이다.
#
# (2) 정답이 정확히 하나 있다고 가정하므로
# 찾는 즉시 return하면 result와 break가 필요 없다.
#
# (3) 이 문제의 핵심은 "조합을 모두 만드는 것"이 아니다.
# 현재 값마다 필요한 상대값을 계산하고,
# 그 값을 이전에 봤는지만 Hash로 확인한다.


# ============================================================
# 7. 시간복잡도
# ============================================================

# 이중 for문:
# O(N^2)
#
# Hash 풀이:
# for문 O(N)
# dict 조회 평균 O(1)
# -> 전체 평균 O(N)
#
# 공간복잡도:
# 최악의 경우 dict에 N개 저장
# -> O(N)


